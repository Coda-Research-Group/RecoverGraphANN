#!/usr/bin/env python
"""Table 1 — the effect of the transformation on HNSW's neighbor-selection heuristic.

Reproduces `tab:degree`: for each dataset and graph degree M, the average number of accepted
candidates (`acc`), the average node degree (`deg`), and Recall@10, with the transformation
off and on. `efConstruction = 500`, `efSearch = 1000`, k = 10, single-threaded.

This table had no generating script before — its `acc` and `deg` columns were read by hand
out of the raw run logs, which made the paper's most distinctive numbers its least
reproducible ones.

    python experiments/table1_degree.py                 # run it (~2 hours)
    python experiments/table1_degree.py --quick         # 10k subsample, minutes
    python experiments/table1_degree.py --render        # LaTeX from the committed CSV

Writes `results/table1_degree.csv`, and with --render also `results/table1_degree.tex`.
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'src'))

from rgann.datasets import load_dataset
from rgann.runner import ExperimentSpec, append_rows, atomic_output, run_spec
from rgann.transform import Normalization

DATASETS = ('yi-128-ip', 'llama-128-ip')
M_VALUES = (4, 16, 48, 96)
EF_CONSTRUCTION = 500
EF_SEARCH = 1000
K = 10

DEFAULT_CSV = Path('results/table1_degree.csv')

#: `--quick` numbers come from a 10k subsample and are not the paper's, so they are kept out
#: of the committed path rather than written over it.
QUICK_CSV = Path('results/quick/table1_degree.csv')
DEFAULT_TEX = Path('results/table1_degree.tex')

#: Column headers as the paper prints them, mapped to their real names in the CSV.
PAPER_COLUMNS = {'acc': 'accepted_candidates_avg', 'deg': 'avg_node_degree', 'Recall@10': 'recall_avg'}


def specs(*, quick: bool) -> list[ExperimentSpec]:
    """One spec per (dataset, M, normalization) cell of the table."""
    return [
        ExperimentSpec(
            dataset=dataset,
            backend='hnsw-hnswlib',
            normalization=normalization,
            build_params={'m': m, 'ef_construction': EF_CONSTRUCTION},
            search_values=[EF_SEARCH],
            k=K,
            threads=1,
            label='table1' + ('-quick' if quick else ''),
        )
        for dataset in DATASETS
        for m in M_VALUES
        for normalization in (Normalization.NONE, Normalization.BACHRACH)
    ]


def run(output: Path, *, quick: bool) -> None:
    with atomic_output(output) as partial:
        for dataset_name in DATASETS:
            dataset = load_dataset(dataset_name, quick=quick)
            print(dataset.describe(), flush=True)
            for spec in specs(quick=quick):
                if spec.dataset != dataset_name:
                    continue
                # Flush after every spec: a build here is tens of minutes and should not be
                # lost to an interruption during a later one.
                append_rows(partial, list(run_spec(spec, dataset)))

    print(f'\nwrote {output}', flush=True)


def render(source: Path, output: Path) -> None:
    """Emit the LaTeX body of Table 1 from the CSV, so the two cannot drift apart."""
    with source.open(newline='') as handle:
        rows = list(csv.DictReader(handle))

    cells: dict[tuple[str, int, str], dict[str, str]] = {}
    for row in rows:
        key = (row['dataset_name'], int(float(row['m'])), row['normalization'])
        cells[key] = row

    lines = [
        r'% Generated by experiments/table1_degree.py --render. Do not edit by hand.',
        r'\begin{tabular}{@{}lrcccccc@{}}',
        r'\toprule',
        r'& & \multicolumn{3}{c}{Raw} & \multicolumn{3}{c}{Transformed} \\',
        r'\cmidrule(lr){3-5} \cmidrule(lr){6-8}',
        (
            r'Dataset & $M$ & \texttt{acc} & \texttt{deg} & Recall@10 & '
            r'\texttt{acc} & \texttt{deg} & Recall@10 \\'
        ),
        r'\midrule',
    ]

    for index, dataset_name in enumerate(DATASETS):
        if index:
            lines.append(r'\midrule')
        lines.append(rf'\multirow{{{len(M_VALUES)}}}{{*}}{{\texttt{{{dataset_name}}}}}')
        for m in M_VALUES:
            values = []
            for normalization in (Normalization.NONE, Normalization.BACHRACH):
                row = cells.get((dataset_name, m, str(normalization)))
                if row is None:
                    values += ['--', '--', '--']
                    continue
                values += [
                    f'{float(row["accepted_candidates_avg"]):.1f}',
                    f'{float(row["avg_node_degree"]):.1f}',
                    rf'{float(row["recall_avg"]) * 100:.1f}\%',
                ]
            lines.append(f' & {m:<3} & ' + ' & '.join(values) + r' \\')

    lines += [r'\bottomrule', r'\end{tabular}']
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines) + '\n')
    print(f'wrote {output}')


def resolve_csv(chosen: Path | None, *, quick: bool) -> Path:
    """Where to write, when the caller did not say."""
    if chosen is not None:
        return chosen
    return QUICK_CSV if quick else DEFAULT_CSV


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--csv', type=Path, default=None, help='results CSV to write, or read with --render')
    parser.add_argument('--output', type=Path, default=DEFAULT_TEX, help='LaTeX file to write with --render')
    parser.add_argument('--render', action='store_true', help='emit LaTeX from an existing CSV; run nothing')
    parser.add_argument('--quick', action='store_true', help='10k-row subsample; NOT the paper numbers')
    args = parser.parse_args()

    csv_path = resolve_csv(args.csv, quick=args.quick)

    if args.render:
        if not csv_path.exists():
            parser.error(f'{csv_path} does not exist; run without --render first')
        render(csv_path, args.output)
        return

    run(csv_path, quick=args.quick)


if __name__ == '__main__':
    main()
